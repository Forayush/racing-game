// The championship calendar. Each layout is a "turtle path" modelled on a real Grand Prix circuit:
// straights in metres, corners as [direction, angle°, radius m]. The builder closes the loop and
// scales it to `lengthKm` (circuits run at ~60% of real-world size so laps last 40–65 seconds).

export type PathStep = ['S', number] | ['R' | 'L', number, number];

export type SceneryKind = 'parkland' | 'street' | 'forest' | 'airfield' | 'desert' | 'alpine';

export interface CircuitDef {
  id: string;
  round: number;
  /** Grand Prix name. */
  gp: string;
  circuit: string;
  city: string;
  country: string;
  /** In-game lap length. */
  lengthKm: number;
  turns: number;
  /** +1 clockwise, -1 anticlockwise, 0 figure-of-eight. */
  winding: 1 | -1 | 0;
  /** Palette id from themes.ts. */
  palette: string;
  scenery: SceneryKind;
  /** Barriers hug the track: hitting them costs speed (street circuits). */
  walls: boolean;
  description: string;
  path: PathStep[];
  /** [lap fraction, metres] keyframes, real-world scale. */
  elevation: [number, number][];
}

